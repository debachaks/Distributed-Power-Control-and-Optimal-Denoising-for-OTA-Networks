def best_response(P_init, h, eta, c, epsilon_p, P_max_vec, max_iter_inner):
    """
    Inner loop: iterates over P until convergence.
    """
    P_current = P_init.copy()
    utilities_prev = utility_vector(P_current, h, c, eta)
