def safe_exp(x: np.ndarray) -> np.ndarray:
    """Safe exponential with clipping to avoid overflow."""
    return np.exp(np.clip(x, -SAFE_MARGIN, SAFE_MARGIN))


def utility_vector(
    P: npt.NDArray[np.float64],
    h: npt.NDArray[np.float64],
    c: np.float64,
    eta: np.float64
):
    utilities = np.zeros(len(P))
    sum1 = 0.0
    for i in range(len(P)):
        sum1 += h[i] * np.sqrt(P[i]) / np.sqrt(eta)

    # Compute adaptive safety scaling
    max_other = 0.0
    for i in range(len(P)):
        me = h[i] * np.sqrt(P[i]) / np.sqrt(eta)
        other = sum1 - me
        max_other = max(max_other, abs(other))

    safe_limit = SAFE_MARGIN / (2 * max_other) if max_other > 0 else 1.0
    global EXP_POWER_UTILITY
    if EXP_POWER_UTILITY > safe_limit:
        print(f"EXP_POWER_UTILITY ({EXP_POWER_UTILITY}) too large for data; "
              f"reducing to {safe_limit:.4e}.")
        EXP_POWER_UTILITY = safe_limit

    # Compute utilities safely
    for i in range(len(P)):
        me = h[i] * np.sqrt(P[i]) / np.sqrt(eta)
        other = sum1 - me
        exp_arg = EXP_POWER_UTILITY * other
        utilities[i] = me * safe_exp(exp_arg) - c * np.power(me, 2)

    return utilities


def closed_form_p_star(
    h: npt.NDArray[np.float64],
    c: np.float64,
    eta: np.float64,
    P_max: npt.NDArray[np.float64],
    P: npt.NDArray[np.float64]
):
    sum1 = 0.0
    for i in range(len(P)):
        sum1 += h[i] * np.sqrt(P[i]) / np.sqrt(eta)

    P_star = np.zeros(len(P))

    # Compute adaptive safety scaling
    max_other = 0.0
    for i in range(len(P)):
        me = h[i] * np.sqrt(P[i]) / np.sqrt(eta)
        other = sum1 - me
        max_other = max(max_other, abs(other))

    safe_limit = SAFE_MARGIN / (2 * max_other) if max_other > 0 else 1.0
    global EXP_POWER_UTILITY
    if EXP_POWER_UTILITY > safe_limit:
        print(f" EXP_POWER_UTILITY ({EXP_POWER_UTILITY}) too large deba for data; "
              f"reducing to {safe_limit:.4e}.")
        EXP_POWER_UTILITY = safe_limit

    # Compute P_star safely
    for i in range(len(P)):
        me = h[i] * np.sqrt(P[i]) / np.sqrt(eta)
        other = sum1 - me
        exp_arg2 = 2 * EXP_POWER_UTILITY * other
        P_star[i] = eta * safe_exp(exp_arg2) / (4 * np.power(c, 2) * np.power(h[i], 2))

    P_star = np.clip(P_star, 0, P_max)
    return P_star

def optimal_eta(h, P, sigma2):

    h = np.array(h)
    P = np.array(P)

    numerator = np.sum(h**2 * P) + sigma2
    denominator = np.sum(h * np.sqrt(P))

    eta_star = (numerator / denominator)**2
    return eta_star
